import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const base = new URL('./app/', import.meta.url);
const ctx = vm.createContext({window: {}, console});
for (const file of ['kit/js/dk-dashboard.js', 'kit/js/family-mortgage-data.js']) vm.runInContext(readFileSync(new URL(file,base),'utf8'),ctx);
const source = JSON.parse(readFileSync(new URL('data/mortgage-source.json',base),'utf8'));
const model = ctx.window.familyMortgageData;
const all = model.select(source);
assert.equal(all.counts.total,2); assert.equal(all.counts.behind,2); assert.equal(all.counts.crit,2); assert.equal(all.counts.missing,0);
assert.equal(all.kpis.issued,100); assert.equal(all.kpis.issuedPlan,200); assert.equal(all.kpis.planPct,50);
assert.equal(all.ranking[0].id,'altai-rep'); assert.equal(all.ranking[0].lag,60);
const nw = model.select(source,{district:'СЗФО'});
assert.equal(nw.counts.total,1); assert.equal(nw.kpis.issued,40); assert.equal(nw.kpis.issuedPlan,50); assert.equal(nw.kpis.planPct,80); assert.equal(nw.regions[0].lag,20); assert.equal(nw.regions[0].status,'crit');
const spb=nw.regions[0]; assert.equal(spb.monthly[0].issued,10); assert.equal(spb.monthly[0].planPct,50); assert.equal(spb.monthly[1].issued,30); assert.equal(spb.monthly[1].planPct,100); assert.equal(spb.monthly[1].status,'calm');
const zero=all.regions.find(r=>r.id==='altai-rep').monthly[1]; assert.equal(zero.issued,0); assert.equal(zero.planPct,0); assert.equal(zero.lag,100); assert.equal(zero.status,'crit');
const partial=structuredClone(source); partial.rows[0].values.issued=null;
const missing=model.select(partial); assert.equal(missing.kpis.issued,null); assert.equal(missing.counts.missing,1); assert.equal(missing.regions.find(r=>r.id==='spb').status,'missing');
const empty=model.select(source,{district:'unknown'}); assert.equal(empty.counts.total,0); assert.equal(empty.kpis.planPct,null);
console.log('PASS: literal model checks, district, exact boundary, monthly details, zero, null and empty');
